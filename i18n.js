(function () {
    const config = DEVINY_I18N;
    const textEntries = Object.entries(config.text);
    const normalizedText = new Map(textEntries.map(([key, value]) => [normalize(key), { key, value }]));
    const translatedLookup = new Map();

    textEntries.forEach(([key, value]) => {
        Object.values(value).forEach((translation) => {
            translatedLookup.set(normalize(translation), key);
        });
    });

    function normalize(value) {
        return String(value || '').replace(/\s+/g, ' ').trim();
    }

    function getSavedLang() {
        const requestedLang = new URLSearchParams(window.location.search).get('lang');
        if (config.languages[requestedLang]) {
            localStorage.setItem(config.storageKey, requestedLang);
            return requestedLang;
        }

        const saved = localStorage.getItem(config.storageKey);
        if (config.languages[saved]) return saved;

        const browserLang = (navigator.language || '').slice(0, 2).toLowerCase();
        return config.languages[browserLang] ? browserLang : config.defaultLang;
    }

    function getPageKey() {
        const path = window.location.pathname.replace(/\/$/, '').split('/').pop() || 'index';
        if (path.startsWith('about')) return 'about';
        if (path.startsWith('contacts')) return 'contacts';
        if (path.startsWith('team')) return 'team';
        return 'home';
    }

    function translate(key, lang = currentLang()) {
        if (!key) return '';
        if (lang === config.defaultLang) return key;
        return config.text[key]?.[lang] || key;
    }

    function currentLang() {
        return document.documentElement.dataset.lang || getSavedLang();
    }

    function translateMessage(key, lang = currentLang()) {
        return config.messages[key]?.[lang] || config.messages[key]?.[config.defaultLang] || '';
    }

    function translateTextNode(node, lang) {
        const raw = node.nodeValue;
        const normalized = normalize(raw);
        if (!normalized) return;

        if (!node.__devinyI18nKey) {
            const found = normalizedText.get(normalized);
            node.__devinyI18nKey = found?.key || translatedLookup.get(normalized) || null;
        }

        if (!node.__devinyI18nKey) return;

        const leading = raw.match(/^\s*/)?.[0] || '';
        const trailing = raw.match(/\s*$/)?.[0] || '';
        node.nodeValue = `${leading}${translate(node.__devinyI18nKey, lang)}${trailing}`;
    }

    function translateAttribute(element, attr, lang) {
        const raw = element.getAttribute(attr);
        const normalized = normalize(raw);
        if (!normalized) return;

        const storageKey = `__devinyI18n_${attr}`;
        if (!element[storageKey]) {
            const found = normalizedText.get(normalized);
            element[storageKey] = found?.key || translatedLookup.get(normalized) || null;
        }

        if (element[storageKey]) {
            element.setAttribute(attr, translate(element[storageKey], lang));
        }
    }

    function applyTextTranslations(root, lang) {
        const ignored = new Set(['SCRIPT', 'STYLE', 'NOSCRIPT', 'IFRAME']);
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode(node) {
                if (!node.parentElement || ignored.has(node.parentElement.tagName)) {
                    return NodeFilter.FILTER_REJECT;
                }
                return NodeFilter.FILTER_ACCEPT;
            }
        });

        const nodes = [];
        while (walker.nextNode()) nodes.push(walker.currentNode);
        nodes.forEach((node) => translateTextNode(node, lang));

        root.querySelectorAll('[placeholder], [aria-label], [title], [alt]').forEach((element) => {
            ['placeholder', 'aria-label', 'title', 'alt'].forEach((attr) => {
                if (element.hasAttribute(attr)) translateAttribute(element, attr, lang);
            });
        });
    }

    function applyMeta(lang) {
        const meta = config.meta[getPageKey()];
        if (!meta) return;

        document.title = meta.title[lang] || meta.title.en;
        document.querySelector('meta[name="description"]')?.setAttribute('content', meta.description[lang] || meta.description.en);
        document.querySelector('meta[property="og:title"]')?.setAttribute('content', meta.ogTitle[lang] || meta.ogTitle.en);
        document.querySelector('meta[property="og:description"]')?.setAttribute('content', meta.ogDescription[lang] || meta.ogDescription.en);
    }

    function applyHtmlTranslations(lang) {
        document.querySelectorAll('[data-i18n-html]').forEach((element) => {
            const key = element.getAttribute('data-i18n-html');
            const translation = config.html[key]?.[lang] || config.html[key]?.[config.defaultLang];
            if (translation) element.innerHTML = translation;
        });
    }

    function setupSwitcher(lang) {
        document.querySelectorAll('[data-language-current]').forEach((element) => {
            element.textContent = config.languages[lang].short;
        });

        document.querySelectorAll('[data-lang]').forEach((button) => {
            const isActive = button.dataset.lang === lang;
            button.classList.toggle('active', isActive);
            button.setAttribute('aria-pressed', String(isActive));
        });

        document.querySelectorAll('.language-btn').forEach((button) => {
            if (button.__devinyLanguageReady) return;
            button.__devinyLanguageReady = true;
            button.addEventListener('click', (event) => {
                event.stopPropagation();
                const switcher = button.closest('.language-switcher');
                switcher?.classList.toggle('is-open');
            });
        });

        document.querySelectorAll('[data-lang]').forEach((button) => {
            if (button.__devinyLanguageReady) return;
            button.__devinyLanguageReady = true;
            button.addEventListener('click', (event) => {
                event.stopPropagation();
                setLanguage(button.dataset.lang);
                button.closest('.language-switcher')?.classList.remove('is-open');
            });
        });

        if (!document.__devinyLanguageCloseReady) {
            document.__devinyLanguageCloseReady = true;
            document.addEventListener('click', () => {
                document.querySelectorAll('.language-switcher.is-open').forEach((switcher) => {
                    switcher.classList.remove('is-open');
                });
            });
        }
    }

    function applyLanguage(lang = currentLang()) {
        const safeLang = config.languages[lang] ? lang : config.defaultLang;
        document.documentElement.lang = config.languages[safeLang].htmlLang;
        document.documentElement.dataset.lang = safeLang;
        applyMeta(safeLang);
        applyHtmlTranslations(safeLang);
        applyTextTranslations(document.body, safeLang);
        setupSwitcher(safeLang);
    }

    function setLanguage(lang) {
        if (!config.languages[lang]) return;
        localStorage.setItem(config.storageKey, lang);
        applyLanguage(lang);
    }

    window.DevinyI18n = {
        init: () => applyLanguage(getSavedLang()),
        setLanguage,
        currentLang,
        t: translate,
        message: translateMessage
    };
})();
